const TABLES: Record<Lang, Partial<Record<Key, string>>> = { en, ko }

export function pickLang(locale: string | null | undefined): Lang {
  return String(locale || '').toLowerCase().startsWith('ko') ? 'ko' : 'en'
}

export function has(key: string): key is Key {
  return key in en
}

export function t(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  const template = TABLES[lang][key] ?? en[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`))
}

/** Text for an action result: a success key, a known error code, or the raw message. */
export function resultText(lang: Lang, r: { ok: boolean; message: string; code?: string; key?: string; params?: Record<string, string | number> }): string {
  if (r.key && has(r.key)) return t(lang, r.key, r.params)
  if (!r.ok && r.code && has(`err.${r.code}`)) return t(lang, `err.${r.code}` as Key)
  return r.message
}
